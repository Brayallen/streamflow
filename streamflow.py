import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

L = 6
RA = 170
RB = 410
P1 = 100
q1 = 120
q2 = 120

x = np.linspace(0, L, 500)

V = np.zeros_like(x)

for i in range(len(x)):
    if x[i] < 2:
        V[i] = RA - (q1 * x[i])
    elif x[i] < 4:
        V[i] = RA - (q1 * 2) - P1

    else:
        V[i] = RA - (q1 *2) - P1 + RB - (q2 * (x[i] -4))

plt.figure(figsize=(8, 5))
plt.plot(x,V)
plt.fill_between(x, V, 0, alpha=0.4)
plt.axhline(0, color='black', linewidth=1)

plt.title('Shear Diagram')
plt.xlabel('x (ft)')
plt.ylabel('V (lb)')
plt.xlim(0,L)
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

L = 6
RA = 170
RB = 410
P1 = 100
q1 = 120
q2 = 120

x = np.linspace(0, L, 500)

M = np.zeros_like(x)

for i in range(len(x)):
    if x[i] < 2:
      M[i] = (RA * x[i]) - (q1 * x[i]**2/2)

    elif x[i] < 4:
        M[i] = (RA * x[i]) - (q1 * 2 * (x[i] -1)) - (P1 * x[i] - 2)
    else:
        M[i] = (RA * x[i]) - (q1 * 2 * (x[i] - 1)) - (P1 * (x[i] - 2)) +(RB * (x[i] - 4)) - (q2 * (x[i]- 4)**2 / 2)

plt.figure(figsize=(8, 5))
plt.plot(x, M)
plt.fill_between(x, M, 0, alpha=0.4)
plt.axhline(0, color='black', linewidth=1)

plt.title('Moment Diagram')
plt.xlabel('x (ft)')
plt.ylabel('M (lb-ft)')
plt.xlim(0, L)
plt.show()

